import assert from "node:assert/strict";
import { zeroed } from "../../packages/typescript/dist/index.js";
import { MessageView, MaybeScalarView, NestedView, BoxedLeafView, NoFactoryView, EmptyPayloadsView } from "../../target/replacement/bindings.js";

const view = MessageView.create({ before: 123, fixed: { maybe: null, nested: { value: null }, choice: { kind: 0 /* ChoiceKind.Empty */ } }, items: [null], text: "preserved", after: 456 });
const alias = new MessageView(view.bytes);
const fixed = alias.fixed;
assert.equal(fixed.maybe, null);
assert.equal(fixed.nested.value, null);
assert.equal(fixed.choice.childLeaf, undefined);
const leaf = { number: 7, scalar: 8 };
const boxed = BoxedLeafView.create(null);
const boxedAlias = new BoxedLeafView(boxed.bytes);
assert.equal(boxedAlias.value, null);
boxed.set(leaf);
assert.equal(boxedAlias.value.number, 7);
boxed.set(null);
assert.equal(boxedAlias.value, null);
view.fixed.setMaybe(leaf);
assert.equal(fixed.maybe.number, 7);
assert.equal(fixed.maybe, fixed.maybe);
view.fixed.setNested({ value: leaf });
assert.equal(fixed.nested.value.number, 7);
view.fixed.choice.replace({ kind: 1 /* ChoiceKind.Child */, leaf });
assert.equal(fixed.choice.childLeaf.number, 7);
view.fixed.choice.replace({ kind: 2 /* ChoiceKind.Numbers */, values: [1,2,3] });
assert.equal(fixed.choice.childLeaf, undefined);
assert.deepEqual([...fixed.choice.numbersValues], [1,2,3]);
view.fixed.choice.setNumbersValues(zeroed());
assert.deepEqual([...fixed.choice.numbersValues], [0,0,0]);
view.fixed.setMaybe(null);
view.fixed.setNested({ value: null });
assert.equal(fixed.maybe, null);
assert.equal(fixed.nested.value, null);
view.fixed.setNested(null);
assert.equal(fixed.nested, null);
view.items.set(0, leaf);
assert.equal(alias.items.get(0).number, 7);
view.items.set(0, null);
assert.equal(alias.items.get(0), null);
const scalar = MaybeScalarView.create(null);
const noFactory = new NoFactoryView(scalar.bytes);
noFactory.replace({ value: 17 });
assert.equal(scalar.value, 17);
scalar.value = 42;
assert.equal(scalar.value, 42);
scalar.value = null;
assert.equal(scalar.value, null);
const nested = NestedView.create(null);
const nestedAlias = new NestedView(nested.bytes);
assert.equal(nestedAlias.value, null);
nested.replace({ value: leaf });
assert.equal(nestedAlias.value.value.number, 7);
nested.replace({ value: null });
assert.equal(nestedAlias.value.value, null);
const emptyPayloads = EmptyPayloadsView.create({ empty: [], nested: [[], []], number: 1 });
const emptyAlias = new EmptyPayloadsView(emptyPayloads.bytes);
const replacement = { empty: [], nested: [[], []], number: 2 };
emptyPayloads.replace(replacement);
assert.equal(emptyAlias.number, 2);
assert.deepEqual([...emptyAlias.bytes], [2, 0, 0, 0]);
assert.equal(emptyAlias.empty.length, 0);
assert.equal(emptyAlias.nested.length, 2);
assert.equal(emptyAlias.nested.get(1).length, 0);
view.fixed.choice.replace({ kind: 3 /* ChoiceKind.EmptyArrays */, data: replacement });
assert.equal(fixed.choice.emptyArraysData.number, 2);
assert.equal(alias.before, 123);
assert.equal(alias.after, 456);
assert.equal(alias.text, "preserved");
console.log("TypeScript: in-place variants, nullable presence, cached aliases, fixed arrays and neighboring payloads passed");
