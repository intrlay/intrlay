import assert from "node:assert/strict";
import { NamingSampleView } from "../../target/naming/bindings.js";
import { ItemsView as StaticCollectionView } from "../../target/naming/collection-static.js";
import { ItemsView as OmittedCollectionView } from "../../target/naming/collection-omitted.js";
import { checkPublicStorage } from "../../target/naming/public-storage.js";
import { PacketView as NumericInputNamesView } from "../../target/naming/numeric-input-names.js";
import { PayloadEventView } from "../../target/naming/enum_properties.js";

const value = { sampleRate: 120, literalName: 0 };
const view = NamingSampleView.Static_Create(value);
assert.equal(view.sampleRate, 120);
assert.equal(view.literalName, 0);
view.sampleRate = 144;
assert.equal(view.sampleRate, 144);
assert.equal(view.storage.bytes.length, NamingSampleView.Static_ComputeByteLength(value));

const collection = StaticCollectionView.create([0, 0]);
assert.equal(StaticCollectionView.byteSizeLength, 8);
assert.equal(collection.byteSizeLength, 2);
assert.equal(collection.get(1), 0);
const strings = OmittedCollectionView.create(["one", "two"]);
assert.equal(strings.setLength, 2);
assert.equal(strings.getLength(1), "two");
assert.equal(checkPublicStorage(), true);

const numeric = NumericInputNamesView.create({ payload: new Uint32Array([17, 19, 23]) });
assert.deepEqual([...numeric.payload], [17, 19, 23]);
assert.deepEqual([...numeric.storage.bytes], [17, 0, 0, 0, 19, 0, 0, 0, 23, 0, 0, 0]);
numeric.setPayload(new Uint32Array([29, 31, 37]));
assert.deepEqual([...numeric.payload], [29, 31, 37]);
assert.deepEqual([...numeric.storage.bytes], [29, 0, 0, 0, 31, 0, 0, 0, 37, 0, 0, 0]);
const payload = PayloadEventView.create({ kind: 1 /* VariantTaskDone */, input_request_id: 7, input_saved_id: 11 });
assert.equal(payload.write_task_done_request_id, 7);
payload.write_task_done_request_id = 19;
assert.equal(payload.write_task_done_request_id, 19);
assert.equal(payload.read_task_done_saved_id, 11);
assert.equal(Object.getOwnPropertyDescriptor(PayloadEventView.prototype, "read_task_done_saved_id").set, undefined);
payload.replace({ kind: 2 /* Delivered */, Ticket: 23 });
assert.equal(payload.write_delivered_ticket, 23);
payload.write_delivered_ticket = 29;
assert.equal(payload.write_delivered_ticket, 29);
assert.equal(payload.write_task_done_request_id, undefined);
payload.replace({ kind: 3 /* VariantFlattened */, input_payload: { input_request_id: 31 } });
assert.equal(payload.write_flattened_payload_request_id, 31);
payload.write_flattened_payload_request_id = 37;
assert.equal(payload.write_flattened_payload_request_id, 37);
payload.replace({ kind: 4 /* VariantSetOnly */, input_request_id: 41 });
payload.setReadSetOnlyRequestId(43);
assert.equal(payload.input_storage.u32[1], 43);
assert.equal(Object.getOwnPropertyDescriptor(PayloadEventView.prototype, "read_set_only_request_id"), undefined);
console.log("TypeScript: naming rules preserve explicit names, property modifiers, and static factories");
