using System;
using System.Linq;
using System.Text;

namespace Intrlay.Generator;

internal sealed partial class Emitter(Schema schema)
{
    private readonly StringBuilder source = new();
    private int indentation;
    private bool scopedView;
    private Node Node(int id) => schema.Nodes[id];
    private string Name(string role) => "@" + schema.Names[role];

    public string Generate()
    {
        Line("// <auto-generated/>");
        Line("#nullable enable");
        Line($"namespace {schema.Namespace};");
        Line();

        InlineArrays();
        foreach (var node in schema.Nodes.Values.Where(node => node.Native)) Native(node);
        foreach (var node in schema.Nodes.Values.Where(node => node.Native && node.SpanInputName.Length != 0)) SpanInput(node);
        SourceInputs();
        Open($"internal static partial class {schema.Name}");
        foreach (var node in schema.Nodes.Values.Where(node => node.Encode))
        {
            if (node.HasPayload) Measure(node);
            Write(node);
            if (ElementSource(node)) SourceCollectionCodec(node);
        }
        foreach (var node in schema.Nodes.Values.Where(node => node.NativeLayout)
            .GroupBy(node => node.NativeReadName).Select(group => group.First())) NativeRead(node);
        Close();
        foreach (var view in schema.Views)
        {
            View(view);
            View(view, scoped: true);
        }
        ScopedOptionals();
        return source.ToString();
    }

    private void Line(string text = "")
    {
        foreach (var line in text.Split('\n'))
        {
            if (line.Length > 0) source.Append(' ', indentation * 4).Append(line);
            source.AppendLine();
        }
    }
    private void Open(string declaration)
    {
        if (declaration.Length != 0) Line(declaration);
        Line("{");
        ++indentation;
    }
    private void Close()
    {
        --indentation;
        Line("}");
    }
    private void Docs(string text)
    {
        if (text.Length == 0) return;
        Line("/// <summary>");
        foreach (var line in text.Replace("\r", "").Split('\n'))
            Line("/// " + line.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;"));
        Line("/// </summary>");
    }

    private string Input(int id, bool qualified = false)
    {
        var node = Node(id);
        if (node.Scalar) return Scalar(node.Kind);
        return node.Kind switch
        {
            "Unit" => "global::System.ValueTuple",
            "String" => "string",
            "Record" or "Enum" => qualified ? $"global::{schema.Namespace}.{node.Name}" : node.Name,
            "Sequence" => $"global::System.ReadOnlyMemory<{Input(node.Value, qualified)}>",
            "Array" => $"{(qualified && !node.ArrayName.StartsWith("global::") ? $"global::{schema.Namespace}." : "")}{node.ArrayName}<{Input(node.Value, qualified)}>",
            "Boxed" => $"global::Intrlay.Box<{Input(node.Value, qualified)}>",
            "Optional" => OptionalType(node.Value, input: true, readOnly: false, qualified),
            _ => throw new InvalidOperationException("Unknown wire kind " + node.Kind),
        };
    }

    private string Output(int id, bool readOnly)
    {
        var node = Node(id);
        if (node.Scalar) return Scalar(node.Kind);
        if (node.ValueEnum) return Input(id);
        return node.Kind switch
        {
            "Unit" => "global::System.ValueTuple",
            "String" => "string",
            "Boxed" => Output(node.Value, readOnly),
            "Optional" => OptionalType(node.Value, input: false, readOnly),
            _ => (scopedView ? node.SpanName : node.ViewName) + (readOnly && node.Write ? "ReadOnly" : ""),
        };
    }

    private string OptionalType(int value, bool input, bool readOnly, bool qualified = false)
    {
        if (!input && scopedView && IsScopedOutput(value)) return ScopedOptionalName(value, readOnly);
        var type = input ? Input(value, qualified) : Output(value, readOnly);
        var payload = OptionalPayload(value, input);
        if (payload.Kind == "Optional") return $"global::Intrlay.Optional<{type}>";
        return payload.Kind is "String" or "Boxed" ? type + "?" : $"global::System.Nullable<{type}>";
    }

    private string Bytes(string buffer) => scopedView ? buffer : buffer + ".Span";

    private Node OptionalPayload(int id, bool input)
    {
        var node = Node(id);
        while (!input && node.Kind == "Boxed") node = Node(node.Value);
        return node;
    }

    private (string Present, string Value) OptionalInput(int value) =>
        Node(value).Kind is "String" or "Boxed"
            ? ("value is not null", "value") : ("value.HasValue", "value.Value");

    private bool Borrows(int id)
    {
        var node = Node(id);
        if (node.ValueEnum) return false;
        return node.Kind switch
        {
            "Record" or "Enum" or "Array" or "Sequence" => true,
            "Optional" or "Boxed" => Borrows(node.Value),
            _ => false,
        };
    }

    private string LoadInline(int id, string offset, bool readOnly, string buffer, string bytes)
    {
        var node = Node(id);
        if (node.Scalar)
        {
            // Give BinaryPrimitives the known scalar width so the JIT can fold
            // its length check into the slice bound instead of checking twice.
            return node.Kind switch
            {
                "Bool" => $"({bytes}[{offset}] != 0)",
                "U8" => $"{bytes}[{offset}]",
                "I8" => $"unchecked((sbyte){bytes}[{offset}])",
                _ => $"global::System.Buffers.Binary.BinaryPrimitives.Read{ScalarMethod(node.Kind)}LittleEndian({bytes}.Slice({offset}, {node.Size}))",
            };
        }
        if (node.ValueEnum)
            return $"({Input(id)})global::System.Buffers.Binary.BinaryPrimitives.ReadUInt32LittleEndian({bytes}.Slice({offset}, 4))";
        return node.Kind switch
        {
            "Unit" => "default(global::System.ValueTuple)",
            "String" => $"global::Intrlay.Reader.StringAt({bytes}, {offset})",
            _ => $"new {Output(id, readOnly)}({buffer}, {offset})",
        };
    }

    private static string Store(Node node, string buffer, string offset, string value) => node.Kind switch
    {
        "Bool" => $"{buffer}[{offset}] = {value} ? (byte)1 : (byte)0;",
        "U8" => $"{buffer}[{offset}] = {value};",
        "I8" => $"{buffer}[{offset}] = unchecked((byte){value});",
        _ => $"global::System.Buffers.Binary.BinaryPrimitives.Write{ScalarMethod(node.Kind)}LittleEndian({buffer}.Slice({offset}, {node.Size}), {value});",
    };

    private static string Scalar(string kind) => kind switch
    {
        "Bool" => "bool", "I8" => "sbyte", "U8" => "byte", "I16" => "short", "U16" => "ushort",
        "I32" => "int", "U32" => "uint", "I64" => "long", "U64" => "ulong", "F32" => "float", "F64" => "double",
        _ => throw new InvalidOperationException("Not a scalar: " + kind),
    };
    private static string ScalarMethod(string kind) => kind switch
    {
        "I16" => "Int16", "U16" => "UInt16", "I32" => "Int32", "U32" => "UInt32",
        "I64" => "Int64", "U64" => "UInt64", "F32" => "Single", "F64" => "Double",
        _ => throw new InvalidOperationException("Not a multi-byte scalar: " + kind),
    };
}
