pub fn generate(
    generation: &GenerationPlan,
    _options: &crate::GenerateOptions,
) -> Result<String, GenerateError> {
    name_validation::validate(generation)?;
    let plan = &generation.encoding.types;
    let mut output = String::from(
        "// @generated by Intrlay. DO NOT EDIT.\n#![allow(\n    dead_code,\n    missing_docs,\n    nonstandard_style,\n    reason = \"Generated APIs preserve schema names and expose fields independently of local usage\"\n)]\n\n//! Intrlay source types. Derive supplies the corresponding encoding inputs and buffer views.\n\n",
    );
    output.push_str(
        "//! Construction and mutation inputs, including nested views, must not overlap the bytes being written.\n//! Writers rely on this caller precondition; no runtime overlap check is performed.\n\n",
    );
    for node in &plan.nodes {
        match &node.kind {
            Kind::Record(fields) => {
                documentation::write(&mut output, &node.docs, "")?;
                writeln!(
                    output,
                    "#[derive(Debug, PartialEq, ::intrlay::Intrlay)]\n#[repr(C, align({}))]",
                    node.layout.alignment(),
                )?;
                if node.transparent {
                    writeln!(output, "#[intrlay(transparent)]")?;
                }
                construction_option(&mut output, &node.options)?;
                writeln!(output, "pub struct {} {{", node.name)?;
                for field in fields {
                    documentation::write(&mut output, &field.docs, "    ")?;
                    field_name(&mut output, field, "    ")?;
                    writeln!(output, "    pub {}: {},", field.name, ty(plan, field.ty))?;
                }
                writeln!(output, "}}\n")?;
            }
            Kind::Enum(variants) => {
                documentation::write(&mut output, &node.docs, "")?;
                writeln!(
                    output,
                    "#[derive(Debug, PartialEq, ::intrlay::Intrlay)]\n#[repr(align({}))]",
                    node.layout.alignment()
                )?;
                if node.transparent {
                    writeln!(output, "#[intrlay(transparent)]")?;
                }
                construction_option(&mut output, &node.options)?;
                writeln!(output, "pub enum {} {{", node.name)?;
                for variant in variants {
                    enum_variant(&mut output, plan, variant)?;
                }
                writeln!(output, "}}\n")?;
            }
            _ => {}
        }
    }
    let mut buffer = String::from("B");
    while plan.exports.contains_key(&buffer)
        || plan
            .nodes
            .iter()
            .any(|node| node.name == buffer || node.view_name == buffer)
    {
        buffer.push('_');
    }
    for (name, id) in &plan.exports {
        let declared = matches!(plan.nodes[*id].kind, Kind::Record(_) | Kind::Enum(_));
        if !declared || *name != plan.nodes[*id].name {
            writeln!(
                output,
                "/// Exported concrete schema type.\npub type {name} = {};",
                ty(plan, *id)
            )?;
            if declared {
                writeln!(
                    output,
                    "pub use {}Input as {name}Input;",
                    plan.nodes[*id].name
                )?;
                writeln!(
                    output,
                    "pub type {name}View<{buffer}> = {}View<{buffer}>;",
                    plan.nodes[*id].name
                )?;
            } else {
                writeln!(
                    output,
                    "pub type {name}View<{buffer}> = ::intrlay::ValueView<{}, {buffer}>;",
                    ty(plan, *id)
                )?;
            }
        }
    }
    Ok(output)
}

fn enum_variant(
    output: &mut String,
    plan: &TypeGraph,
    variant: &crate::plan::Variant,
) -> Result<(), GenerateError> {
    documentation::write(output, &variant.docs, "    ")?;
    writeln!(output, "    #[intrlay(tag = {})]", variant.tag)?;
    if variant.fields.is_empty() {
        writeln!(output, "    {},", variant.name)?;
    } else if variant.synthetic_payload {
        writeln!(
            output,
            "    {}({}),",
            variant.name,
            ty(plan, variant.fields[0].ty)
        )?;
    } else {
        writeln!(output, "    {} {{", variant.name)?;
        for field in &variant.fields {
            documentation::write(output, &field.docs, "        ")?;
            field_name(output, field, "        ")?;
            writeln!(output, "        {}: {},", field.name, ty(plan, field.ty))?;
        }
        writeln!(output, "    }},")?;
    }
    Ok(())
}

fn field_name(
    output: &mut String,
    field: &crate::plan::Field,
    indent: &str,
) -> Result<(), GenerateError> {
    if field.name != field.property_name {
        writeln!(
            output,
            "{indent}#[intrlay(rust(name = {:?}))]",
            field.property_name
        )?;
    }
    Ok(())
}

fn construction_option(output: &mut String, options: &Options) -> Result<(), GenerateError> {
    if !options.generation.create {
        writeln!(output, "#[intrlay(create = false)]")?;
    }
    Ok(())
}

fn ty(plan: &TypeGraph, id: Id) -> String {
    match &plan.nodes[id].kind {
        Kind::Scalar(scalar) => match scalar {
            Scalar::Bool => "::core::primitive::bool",
            Scalar::I8 => "::core::primitive::i8",
            Scalar::U8 => "::core::primitive::u8",
            Scalar::I16 => "::core::primitive::i16",
            Scalar::U16 => "::core::primitive::u16",
            Scalar::I32 => "::core::primitive::i32",
            Scalar::U32 => "::core::primitive::u32",
            Scalar::I64 => "::core::primitive::i64",
            Scalar::U64 => "::core::primitive::u64",
            Scalar::F32 => "::core::primitive::f32",
            Scalar::F64 => "::core::primitive::f64",
        }
        .into(),
        Kind::Unit => "()".into(),
        Kind::String => "::std::string::String".into(),
        Kind::Record(_) | Kind::Enum(_) => plan.nodes[id].name.clone(),
        Kind::Sequence(element) => format!("::std::vec::Vec<{}>", ty(plan, *element)),
        Kind::Array { element, length } => format!("[{}; {length}]", ty(plan, *element)),
        Kind::Optional { value, .. } => format!("::core::option::Option<{}>", ty(plan, *value)),
        Kind::Boxed(value) => format!("::std::boxed::Box<{}>", ty(plan, *value)),
    }
}
